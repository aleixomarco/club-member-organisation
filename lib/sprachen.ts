/* Nur Deutsch ist fest dabei - es ist der Rueckfall in uebersetze() und muss
   deshalb immer da sein. Die uebrigen sechs kommen erst, wenn jemand sie
   wirklich braucht (spracheLaden). Gemessen am 28.09.2026 macht das 195 KB
   gezippt aus, die vorher JEDER mitgeladen hat - auch wer die App nie in einer
   anderen Sprache benutzt. */
const WOERTERBUECHER: Record<string, Woerterbuch> = { de };

const NACHLADER: Record<string, () => Promise<{ default: Woerterbuch }>> = {
  en: () => import("./sprachen/en"),
  es: () => import("./sprachen/es"),
  pt: () => import("./sprachen/pt"),
  it: () => import("./sprachen/it"),
  tr: () => import("./sprachen/tr"),
  fr: () => import("./sprachen/fr"),
};

/* Laedt das Woerterbuch einer Sprache nach.
   Gibt true zurueck, wenn dabei wirklich etwas Neues dazukam - dann muss sich
   die Ansicht erneuern, sonst stuende weiter der deutsche Text da.
   Schlaegt das Laden fehl (kein Netz, Brocken nicht erreichbar), bleibt es bei
   Deutsch. Das ist unschoen, aber die App laeuft weiter - genau dafuer gibt es
   den Rueckfall. */
export async function spracheLaden(code: string): Promise<boolean> {
  if (!code || code === "de" || WOERTERBUECHER[code]) return false;
  const lader = NACHLADER[code];
  if (!lader) return false;
  try {
    WOERTERBUECHER[code] = (await lader()).default;
    return true;
  } catch {
    return false;
  }
}

export const SPRACHE_SPEICHER = "cmo.sprache";

/* Die gewaehlte Sprache aus dem Geraet lesen.
   Sie steht dort UND am Konto: Im Geraet, weil die Wahl vor der Anmeldung
   getroffen wird und es dann noch kein Konto gibt; am Konto, damit sie auf
   einem zweiten Geraet nicht erneut abgefragt wird. */
export function gespeicherteSprache(): Sprachcode | null {
  if (typeof window === "undefined") return null;
  try {
    const wert = window.localStorage.getItem(SPRACHE_SPEICHER);
    return SPRACHEN.some((s) => s.code === wert) ? (wert as Sprachcode) : null;
  } catch {
    /* Privater Modus, gesperrte Website-Daten: Dann wird eben jedes Mal
       gefragt - besser als ein Absturz beim Start. */
    return null;
  }
}

export function spracheMerken(code: string) {
  if (typeof window === "undefined") return;
  try { window.localStorage.setItem(SPRACHE_SPEICHER, code); } catch { /* siehe oben */ }
}

/* Sprache aus dem Accept-Language-Kopf.
   Fuer Seiten, die auf dem Server gezeichnet werden (/willkommen,
   /konto-loeschen): Dort gibt es kein localStorage mit der gewaehlten
   Sprache. Die Reihenfolge im Kopf ist die Vorliebe des Browsers - die
   erste der sieben Sprachen gewinnt, sonst Deutsch. */
export function spracheAusKopf(kopf: string | null | undefined): Sprachcode {
  const codes = String(kopf || "").split(",").map((teil) => teil.trim().slice(0, 2).toLowerCase());
  const treffer = codes.find((code) => SPRACHEN.some((s) => s.code === code));
  return (treffer as Sprachcode | undefined) || "de";
}

/* Uebersetzen. Fehlt ein Schluessel, kommt der deutsche Text - nicht der
   Schluessel. Ein deutscher Satz ist unschoen, "profil.titel" ist unbrauchbar. */
export function uebersetze(code: string, schluessel: string): string {
  return WOERTERBUECHER[code]?.[schluessel] ?? de[schluessel] ?? schluessel;
}
